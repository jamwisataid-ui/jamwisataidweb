/** Case/diacritic-insensitive search over number, latin and meaning. */
export function searchAsmaulHusna(query: string, items: AsmaulHusna[] = asmaulHusna) {
  const normalize = (value: string) => value.toLocaleLowerCase("id-ID").normalize("NFD").replace(/[̀-ͯ'’\-\s]/g, "");
  const needle = normalize(query.trim());
  if (!needle) return items;
  return items.filter((item) => String(item.number) === query.trim() || normalize(item.latin).includes(needle) || normalize(item.meaning).includes(needle) || item.arabic.includes(query.trim()));
}
